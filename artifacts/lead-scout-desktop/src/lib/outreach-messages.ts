import type { Lead } from "@workspace/api-client-react";

export type OutreachMessageFamily = {
  id: string;
  title: string;
  description: string;
  variants: string[];
};

function websiteHost(lead: Lead) {
  if (!lead.website) return null;
  try {
    return new URL(lead.website).hostname.replace(/^www\./, "");
  } catch {
    return null;
  }
}

function auditDetail(lead: Lead) {
  const audit = lead.websiteAudit;
  if (!audit || audit.status !== "checked") {
    return "Если предложение актуально, я сначала покажу несколько конкретных идей по улучшению.";
  }
  const observation = audit.checks.find((check) => check.status === "fail" || check.status === "warn");
  return observation
    ? `В проверке сайта есть пункт «${observation.label}», который можно отдельно разобрать и исправить.`
    : "Я могу показать короткий разбор сайта и предложить только те изменения, которые действительно имеют смысл.";
}

export function createOutreachMessages(lead: Lead): OutreachMessageFamily[] {
  const name = lead.name.trim() || "вашей компании";
  const company = `«${name}»`;
  const host = websiteHost(lead);
  const website = host ? `сайт ${host}` : "ваш сайт";
  const websiteOpening = host
    ? `Увидел сайт ${host} компании ${company}`
    : `Увидел сайт компании ${company}`;

  return [
    {
      id: "commercial",
      title: "Коммерческое предложение",
      description: "Спокойное первое сообщение с понятным предложением.",
      variants: [
        `Здравствуйте, по коммерческому вопросу.\n\nЯ веб-разработчик и по совместительству веб-дизайнер. Решил брать заказы и пополнять портфолио.\n\n${websiteOpening} и считаю, что у него неплохая структура, но с точки зрения дизайна его можно сделать удобнее и визуально приятнее для пользователя: улучшить подачу услуг, цветовую гамму и отдельные недочёты.\n\nПредлагаю бесплатно подготовить для вас макет — дизайн-концепцию сайта. Вы посмотрите результат и сами решите, нужен ли вам такой вариант.\n\nЕсли предложение заинтересует, пожалуйста, дайте обратную связь.`,
        `Здравствуйте! Пишу по поводу сайта ${host ? host : `компании ${company}`}.\n\nЯ занимаюсь веб-разработкой и дизайном. Посмотрел ${website} и вижу, что его можно сделать понятнее для клиента: аккуратнее показать услуги, усилить визуальную подачу и упростить путь до обращения.\n\nГотов бесплатно подготовить дизайн-концепцию одной страницы. Вы сможете оценить идею без обязательств и решить, есть ли смысл продолжать.\n\nЕсли вам интересно, напишите — покажу, что именно предлагаю изменить.`,
        `Добрый день! Я веб-разработчик и веб-дизайнер. Обратил внимание на ${website} ${company}.\n\nУ сайта уже есть основа, но его можно сделать визуально приятнее и понятнее для посетителя. Я могу бесплатно подготовить макет обновлённой страницы с новой цветовой гаммой и более ясной структурой.\n\nВы просто посмотрите результат и решите, подходит ли вам такой подход. Готовы обсудить?`,
      ],
    },
    {
      id: "short",
      title: "Короткое первое сообщение",
      description: "Компактный вариант для первого контакта.",
      variants: [
        `Здравствуйте! Увидел ${website} ${company}. Я веб-разработчик и дизайнер, помогаю улучшать действующие сайты. Могу бесплатно подготовить для вас небольшой макет с идеями по структуре, цветам и удобству. Если интересно — отправлю.`,
        `Добрый день! Посмотрел ${website}. Вижу несколько способов сделать сайт ${company} понятнее и приятнее для клиента. Готов бесплатно показать дизайн-концепцию одной страницы. Кому можно её отправить?`,
        `Здравствуйте! Пишу по поводу ${website}. Я занимаюсь разработкой и дизайном сайтов и хотел бы бесплатно подготовить для ${company} визуальную концепцию улучшенной страницы. Если актуально, дайте знать.`,
      ],
    },
    {
      id: "audit",
      title: "После разбора сайта",
      description: "Сообщение с конкретным наблюдением и следующим шагом.",
      variants: [
        `Здравствуйте! Посмотрел ${website} ${company}. ${auditDetail(lead)}\n\nМогу оформить это в бесплатный макет дизайн-концепции: показать более удобную структуру, визуальную подачу и точки обращения. Вы посмотрите результат и сами решите, нужен ли такой вариант.`,
        `Добрый день! Я сделал первичный разбор ${website}. ${auditDetail(lead)}\n\nПредлагаю не обсуждать абстрактное «обновление сайта», а сначала бесплатно показать конкретный макет для ${company}. Если идея вам подойдёт, обсудим дальнейшие шаги.`,
        `Здравствуйте! Обратил внимание на ${website} ${company}. Есть возможность сделать путь пользователя от просмотра услуг до обращения более понятным. Готов показать это на бесплатной дизайн-концепции и объяснить каждое изменение.`,
      ],
    },
  ];
}