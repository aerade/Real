import type { Lead } from "@workspace/api-client-react";

export type OutreachMessageFamily = {
  id: string;
  title: string;
  description: string;
  variants: string[];
};

function companyTarget(industry: string) {
  const value = industry.toLowerCase();
  if (value.includes("стомат") || value.includes("медиц") || value.includes("клиник")) return "вашей клиники";
  if (value.includes("авто") || value.includes("сто") || value.includes("шином")) return "вашего автосервиса";
  if (value.includes("салон") || value.includes("красот") || value.includes("spa")) return "вашего салона";
  if (value.includes("ресторан") || value.includes("кафе") || value.includes("отел")) return "вашего заведения";
  if (value.includes("недвиж") || value.includes("риэл")) return "вашего агентства";
  if (value.includes("строит")) return "вашей строительной компании";
  return "вашей компании";
}

function verifiedAuditPhrase(lead: Lead) {
  const audit = lead.websiteAudit;
  if (!audit || audit.status !== "checked") {
    return "Если тема актуальна, могу подготовить короткий разбор и предложить несколько вариантов.";
  }

  const observation = audit.checks.find((check) => check.status === "fail" || check.status === "warn");
  if (observation) {
    return `В автоматической проверке публичной страницы есть пункт «${observation.label}», который можно отдельно разобрать и улучшить.`;
  }

  return "Мы уже подготовили короткий автоматический разбор публичной страницы и можем показать его вместе с предложением по следующим шагам.";
}

