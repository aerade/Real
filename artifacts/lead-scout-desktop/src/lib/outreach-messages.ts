import type { Lead } from "@workspace/api-client-react";

export type OutreachMessageFamily = {
  id: string;
  title: string;
  description: string;
  variants: string[];
};

function companyTarget(industry: string) {
  const value = industry.toLowerCase();
  if (value.includes("стомат") || value.includes("медиц") || value.includes("клиник")) return "вашей клиники";
  if (value.includes("авто") || value.includes("сто") || value.includes("шином")) return "вашего автосервиса";
  if (value.includes("салон") || value.includes("красот") || value.includes("spa")) return "вашего салона";
  if (value.includes("ресторан") || value.includes("кафе") || value.includes("отел")) return "вашего заведения";
  if (value.includes("недвиж") || value.includes("риэл")) return "вашего агентства";
  if (value.includes("строит")) return "вашей строительной компании";
  return "вашей компании";
}

function websiteReference(lead: Lead) {
  if (!lead.website) return "онлайн-представления компании";
  try {
    const url = new URL(lead.website);
    return `сайта ${url.hostname.replace(/^www\./, "")}`;
  } catch {
    return "сайта компании";
  }
}

function verifiedAuditPhrase(lead: Lead) {
  const audit = lead.websiteAudit;
  if (!audit || audit.status !== "checked") {
    return "Если тема актуальна, могу посмотреть публичную страницу и предложить несколько понятных улучшений.";
  }

  const observation = audit.checks.find((check) => check.status === "fail" || check.status === "warn");
  if (observation) {
    return `В автоматической проверке публичной страницы есть пункт «${observation.label}», который можно отдельно разобрать и улучшить.`;
  }

  return "Мы уже подготовили короткий разбор публичной страницы и можем показать его вместе с предложением по следующим шагам.";
}

export function createOutreachMessages(lead: Lead): OutreachMessageFamily[] {
  const name = lead.name.trim() || "вашей компании";
  const city = lead.city.trim() || "вашем городе";
  const industry = lead.industry.trim() || "вашей отрасли";
  const target = companyTarget(industry);
  const company = `«${name}»`;
  const website = websiteReference(lead);
  const auditPhrase = verifiedAuditPhrase(lead);

  return [
    {
      id: "first-contact",
      title: "Первое обращение",
      description: "Спокойно начать разговор о сайте, который уже есть у компании.",
      variants: [
        `Здравствуйте! Пишу по поводу ${website} компании ${company}. Мы помогаем сделать действующий сайт понятнее для клиентов и удобнее для обращений. Могу коротко показать, что можно улучшить?`,
        `Здравствуйте! Нашёл ${website} ${company} в ${city}. Мы обновляем сайты так, чтобы посетителю было проще разобраться в услугах и связаться с компанией. Можно отправить несколько идей?`,
        `Добрый день! Обращаюсь по поводу ${website} ${company}. Мы помогаем бизнесу в сфере «${industry}» яснее показывать услуги на уже работающем сайте. Подскажите, кому отправить краткое предложение?`,
        `Здравствуйте! Хотел предложить точечное улучшение ${website} — без обязательной полной переделки. Если актуально, отправлю короткий пример подхода для ${company}.`,
        `Добрый день! Пишу по поводу ${website} ${company}. Готов показать, как сделать путь посетителя от просмотра услуг до обращения короче и понятнее.`,
      ],
    },
    {
      id: "value",
      title: "Через пользу для бизнеса",
      description: "Показать пользу от улучшения существующего сайта.",
      variants: [
        `Здравствуйте! У ${company} уже есть ${website}; мы помогаем сделать на нём услуги, преимущества и способы связи заметнее для потенциального клиента. Могу показать несколько решений?`,
        `Добрый день! Предлагаю посмотреть, где на ${website} ${company} можно сократить путь от интереса до обращения. Обсудим это без обязательств?`,
        `Здравствуйте! Мы улучшаем действующие сайты: структуру услуг, доверие и точки контакта. Могу отправить короткий список идей именно для ${company}.`,
        `Добрый день! Для компании в сфере «${industry}» сайт должен быстро отвечать на вопросы клиента. Готов показать, как это можно усилить на ${website}.`,
        `Здравствуйте! Хотел предложить ${target} точечные изменения на ${website}, которые помогают посетителю быстрее принять решение об обращении. Могу рассказать о подходе?`,
      ],
    },
    {
      id: "service",
      title: "С предложением услуги",
      description: "Предложить обновление уже существующего сайта.",
      variants: [
        `Здравствуйте! Мы помогаем обновлять ${website} компаний в сфере «${industry}»: структура, тексты, визуальная подача и удобный контакт. Можем подготовить отдельную концепцию для ${company}.`,
        `Добрый день! Предлагаем комплексно улучшить ${website} ${company}, не меняя то, что уже работает. Могу показать, как это адаптировать под ${target}?`,
        `Здравствуйте! Мы берём на себя доработку действующих сайтов для бизнеса. Подготовим предложение специально для ${company}, а не общий шаблон. Кому его лучше отправить?`,
        `Добрый день! Если вы хотите получать больше обращений через интернет, можем помочь усилить ${website} и подачу услуг. Готов показать примеры работ.`,
        `Здравствуйте! Работаем с компаниями в сфере «${industry}» и превращаем информацию на действующем сайте в понятный путь к обращению. Могу отправить краткую презентацию?`,
      ],
    },
    {
      id: "audit",
      title: "С опорой на проверку",
      description: lead.websiteAudit?.status === "checked"
        ? "Связывает предложение с подтверждёнными наблюдениями по сайту."
        : "Предлагает начать с проверки действующего сайта.",
      variants: [
        `Здравствуйте! Пишу по поводу ${website} ${company}. ${auditPhrase} Если интересно, покажу, как превратить наблюдения в понятный план улучшений.`,
        `Добрый день! Для ${company} можем подготовить короткий разбор ${website} и предложить приоритетные шаги. ${auditPhrase} Отправить результаты?`,
        `Здравствуйте! Мы провели доступную автоматическую проверку ${website} ${company}. ${auditPhrase} Готов объяснить выводы простым языком и предложить варианты решения.`,
        `Добрый день! Предлагаю начать с небольшого разбора ${website}, а затем выбрать только те изменения, которые действительно имеют смысл. ${auditPhrase}`,
        `Здравствуйте! Могу отправить краткий разбор ${website} и идеи, как усилить путь клиента до обращения для ${company}. ${auditPhrase}`,
      ],
    },
  ];
}