import type { Lead } from "@workspace/api-client-react";

export function createOutreachMessage(lead: Lead): string {
  const name = lead.name.trim() || "вашей компании";
  const industry = lead.industry.trim() || "ваша отрасль";
  const hasWebsite = lead.websiteStatus === "present" && Boolean(lead.website);
  const opening = hasWebsite
    ? `Увидел ваш сайт компании «${name}» (${industry}) и считаю, что сайт имеет неплохую структуру, но с точки зрения дизайна его можно было бы сделать удобнее и визуально приятнее для пользователя, исправить некоторые недочёты, улучшить цветовую гамму.`
    : `Увидел вашу компанию «${name}» (${industry}) и считаю, что ей нужен сайт.`;

  return `Здравствуйте, по коммерческому вопросу

Я веб-разработчик по совместительству веб-дизайнер, решил выполнять заказы, набивать портфолио.

${opening}

${hasWebsite
    ? "Я предлагаю создать для вас бесплатный макет — дизайн-концепцию сайта. Вы посмотрите результат, и если вас заинтересует, то сами решите, нужен ли вам такой вариант. Также могу отправить примеры своих работ (они уже доступны в интернете)."
    : "Сейчас сайт — это главный инструмент для поиска новых клиентов. Он работает 24/7, вызывает больше доверия и помогает выделить компанию среди конкурентов, пока они забирают часть вашей аудитории.\n\nЯ предлагаю создать для вас бесплатный макет — дизайн-концепцию сайта. Вы посмотрите результат, и если вас заинтересует, то сами решите, нужен ли вам такой вариант. Также могу отправить примеры своих работ (они уже доступны в интернете)."}

Если заинтересуетесь, пожалуйста, дайте обратную связь`;
}